/** the custom properties of one theme: Starlight's, then the site's own */
function declarations(p) {
  const d = {
    '--sl-color-white': p.gray[0],
    '--sl-color-black': p.bg,
    '--sl-color-accent-low': p.field,
    '--sl-color-accent': p.ink,
    '--sl-color-accent-high': p.inkHigh,
    '--sl-color-bg-nav': p.bg,
    '--sl-color-bg-sidebar': p.bg,
    '--sl-color-bg-inline-code': p.surface,
    '--sl-color-hairline': p.rule,
    '--sl-color-hairline-light': p.rule,
    '--sl-color-hairline-shade': p.bg,
    '--decl-field': p.field,
    '--decl-tint': p.tint,
  };
  p.gray.slice(1).forEach((c, i) => (d[`--sl-color-gray-${i + 1}`] = c));
  for (const [name, [low, mid, high]] of Object.entries(p.hue)) {
    d[`--sl-color-${name}-low`] = low;
    d[`--sl-color-${name}`] = mid;
    d[`--sl-color-${name}-high`] = high;
  }
  for (const [role, c] of Object.entries(p.syn)) d[`--decl-syn-${role}`] = c;
  for (const [sev, c] of Object.entries(p.sev)) d[`--decl-${sev}`] = c;
  return d;
}

/** src/styles/tokens.css: Starlight keeps the dark theme on :root and stamps light as [data-theme='light'] */
export function tokensCss() {
  const block = (selector, p) =>
    `${selector} {\n${Object.entries(declarations(p))
      .map(([k, v]) => `  ${k}: ${v};`)
      .join('\n')}\n}\n`;
  return (
    '/* generated by scripts/brand.mjs from brand/palette.mjs — edit the palette, not this file */\n' +
    block(':root', palette.dark) +
    block(":root[data-theme='light']", palette.light)
  );
}
