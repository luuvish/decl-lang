// Sync the repository's documentation into the Starlight content tree.
// docs/ stays the single source of truth: this script copies it (and the
// package READMEs) into src/content/docs/, adds the frontmatter Starlight
// needs, rewrites relative links to site routes, and renders the example
// modules with their evaluated output. Generated paths are gitignored.
import { readFileSync, writeFileSync, mkdirSync, rmSync, readdirSync, existsSync, statSync } from 'node:fs';
import { resolve, dirname, posix } from 'node:path';
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';

const SITE = resolve(import.meta.dirname, '..');
const ROOT = resolve(SITE, '..');
const OUT = resolve(SITE, 'src/content/docs');
const SAMPLES = resolve(SITE, 'src/samples/synced');
const BASE = (process.env.SITE_BASE ?? '/decl-lang').replace(/\/$/, '');
const REPO = 'https://github.com/luuvish/decl-lang';
const CLI = resolve(ROOT, 'decl-ts/src/cli.ts');
// the specification's version is the language's: the major and minor of the reference implementation
const SPEC = createRequire(import.meta.url)('decl-lang/package.json').version.split('.').slice(0, 2).join('.');

/** repo-relative source path -> site route (no base, no trailing slash) */
const routes = new Map();
const pages = [];

function add(src, route, extra = {}) {
  routes.set(src, route);
  pages.push({ src, route, ...extra });
}

const list = (dir, ext) => (existsSync(resolve(ROOT, dir)) ? readdirSync(resolve(ROOT, dir)).filter(f => f.endsWith(ext)).sort() : []);

for (const f of list('docs/specification', '.md')) add(`docs/specification/${f}`, `specification/${f.slice(0, -3)}`, { group: 'specification' });
for (const f of list('docs/guide', '.md')) add(`docs/guide/${f}`, `guide/${f.slice(0, -3)}`);
for (const f of list('docs/design', '.md')) add(`docs/design/${f}`, `design/${f.slice(0, -3)}`);
add('docs/REVISIONS.md', 'revisions');
add('docs/README.md', 'documentation', { hidden: true });
// the index of the examples group lives inside its directory so the
// autogenerated sidebar picks it up
add('docs/examples/README.md', 'examples', { title: 'Validation cases', order: 0, file: 'examples/index' });
const exampleTitles = {
  '01_interconnect': 'Hardware interconnect',
  '02_config': 'API/config schema',
  '03_fixtures': 'Test fixture generation',
};
for (const f of list('docs/examples', '.decl')) {
  const stem = f.slice(0, -5);
  add(`docs/examples/${f}`, `examples/${stem}`, { decl: true, title: exampleTitles[stem] ?? stem });
}
// the domain examples: one page per directory, every module's source plus
// the entry module's evaluated output (multi-module: the CLI follows imports)
const domainTitles = {
  svcgraph: 'Service graph (modules and layered deployments)',
  testgen: 'Test generation (comprehension sweeps)',
  fabric: 'Network fabric (scale and corruption probes)',
};
for (const d of (existsSync(resolve(ROOT, 'examples')) ? readdirSync(resolve(ROOT, 'examples')).sort() : [])) {
  const dir = resolve(ROOT, 'examples', d);
  if (!statSync(dir).isDirectory()) continue;
  if (existsSync(resolve(dir, 'README.md'))) { add(`examples/${d}/README.md`, `examples/${d}`, { order: 10 }); continue; }
  const files = readdirSync(dir).filter(f => f.endsWith('.decl')).sort();
  if (!files.length) continue;
  const entry = files.includes('main.decl') ? 'main.decl' : files.length === 1 ? files[0] : null;
  add(`examples/${d}`, `examples/${d}`, { domain: true, files, entry, title: domainTitles[d] ?? d, order: 10 });
}
const toolingTitles = {
  '01_cli': 'Command line',
  '02_repl': 'REPL',
  '03_lsp': 'Language server',
  '04_extension': 'Editor extensions',
  '05_render': 'Renderer',
};
// a tooling document whose Status is "planned" describes a tool that does not
// exist yet; it stays in the repository as a plan and off the site until it ships
const planned = (f) => {
  const lines = readFileSync(resolve(ROOT, 'docs/tooling', f), 'utf8').split('\n');
  const i = lines.findIndex((l) => /^## .*Status/.test(l));
  return i >= 0 && /^Planned\b/.test(lines.slice(i + 1).find((l) => l.trim()) ?? '');
};
for (const f of list('docs/tooling', '.md')) {
  if (planned(f)) continue;
  add(`docs/tooling/${f}`, `tooling/${f.slice(0, -3)}`, { title: toolingTitles[f.slice(0, -3)] ?? f.slice(0, -3) });
}
add('decl-ts/README.md', 'tooling/typescript', { title: 'TypeScript / npm' });
add('decl-py/README.md', 'tooling/python', { title: 'Python / PyPI' });
add('decl-rs/README.md', 'tooling/rust', { title: 'Rust / crates.io' });

// ---------------------------------------------------------------- helpers
const yaml = s => JSON.stringify(s);

function rewriteLinks(md, src) {
  const dir = posix.dirname(src);
  return md.replace(/\]\(([^)\s]+)\)/g, (whole, target) => {
    if (/^(https?:|mailto:|#)/.test(target)) return whole;
    const [path, anchor] = target.split('#');
    const rel = posix.normalize(posix.join(dir, path));
    const route = routes.get(rel);
    if (route) return `](${BASE}/${route}/${anchor ? `#${anchor}` : ''})`;
    if (existsSync(resolve(ROOT, rel))) {
      const kind = statSync(resolve(ROOT, rel)).isDirectory() ? 'tree' : 'blob';
      return `](${REPO}/${kind}/main/${rel}${anchor ? `#${anchor}` : ''})`;
    }
    return whole;
  });
}

function frontmatter(fields) {
  const lines = ['---'];
  for (const [k, v] of Object.entries(fields)) {
    if (v === undefined) continue;
    if (typeof v === 'object' && !Array.isArray(v)) {
      lines.push(`${k}:`);
      for (const [k2, v2] of Object.entries(v)) lines.push(`  ${k2}: ${typeof v2 === 'string' ? yaml(v2) : v2}`);
    } else {
      lines.push(`${k}: ${typeof v === 'string' ? yaml(v) : v}`);
    }
  }
  lines.push('---', '');
  return lines.join('\n');
}

function evaluate(file) {
  try {
    const out = execFileSync('node', [CLI, 'evaluate', file, '--json'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] });
    const rep = JSON.parse(out);
    return rep.ok ? rep.value : null;
  } catch {
    return null;
  }
}

function write(route, text) {
  const file = resolve(OUT, `${route}.md`);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, text);
}

// ---------------------------------------------------------------- generate
for (const d of ['specification', 'guide', 'design', 'examples', 'tooling']) rmSync(resolve(OUT, d), { recursive: true, force: true });
for (const f of ['revisions.md', 'documentation.md', 'examples.md']) rmSync(resolve(OUT, f), { force: true });
rmSync(SAMPLES, { recursive: true, force: true });
mkdirSync(SAMPLES, { recursive: true });

let n = 0;
for (const p of pages) {
  const abs = resolve(ROOT, p.src);
  if (!existsSync(abs)) continue;
  if (p.domain) {
    let body = `Source: [${p.src}/](${REPO}/tree/main/${p.src}) — one of the domain examples that validated the language on real-world shapes (ROADMAP Phase 5).\n`;
    for (const f of p.files) {
      body += `\n## \`${f}\`\n\n\`\`\`decl title=${yaml(f)}\n${readFileSync(resolve(abs, f), 'utf8').trimEnd()}\n\`\`\`\n`;
    }
    const value = p.entry ? evaluate(resolve(abs, p.entry)) : null;
    if (value && typeof value === 'object') {
      body += `\n## Evaluated output\n\nWhat \`decl evaluate ${p.entry}\` prints, one section per \`output\`.\n`;
      for (const [name, v] of Object.entries(value)) body += `\n### \`${name}\`\n\n\`\`\`json\n${JSON.stringify(v, null, 2)}\n\`\`\`\n`;
    }
    write(p.route, frontmatter({ title: p.title, slug: p.route, editUrl: false, sidebar: { order: p.order ?? 10 } }) + body);
    n++;
    continue;
  }
  if (p.decl) {
    const source = readFileSync(abs, 'utf8');
    writeFileSync(resolve(SAMPLES, posix.basename(p.src)), source);
    const value = evaluate(abs);
    let body = `Source: [${p.src}](${REPO}/blob/main/${p.src}) · part of the [validation cases](${BASE}/examples/).\n\n`;
    body += `\`\`\`decl title=${yaml(posix.basename(p.src))}\n${source.trimEnd()}\n\`\`\`\n`;
    if (value && typeof value === 'object') {
      body += `\n## Evaluated output\n\nWhat \`decl evaluate ${posix.basename(p.src)}\` prints, one section per \`output\`.\n`;
      for (const [name, v] of Object.entries(value)) {
        body += `\n### \`${name}\`\n\n\`\`\`json\n${JSON.stringify(v, null, 2)}\n\`\`\`\n`;
      }
    }
    write(p.route, frontmatter({ title: p.title, slug: p.route, editUrl: false, sidebar: { order: p.order ?? 5 } }) + body);
    n++;
    continue;
  }
  let md = readFileSync(abs, 'utf8');
  const m = md.match(/^# (.+)\n/);
  const title = p.title ?? (m ? m[1].trim() : posix.basename(p.src, '.md'));
  if (m) md = md.slice(m[0].length);
  md = rewriteLinks(md, p.src);
  const fm = {
    title,
    slug: p.route,
    editUrl: `${REPO}/edit/main/${p.src}`,
    sidebar: p.hidden ? { hidden: true } : p.order !== undefined ? { order: p.order } : undefined,
  };
  let banner = '';
  if (p.group === 'specification') {
    banner = ':::note[Normative]\nThis chapter is part of the frozen v' + SPEC + ' specification — the single source of truth for every implementation. Changes land as recorded [revisions](' + BASE + '/revisions/).\n:::\n\n';
  }
  write(p.file ?? p.route, frontmatter(fm) + banner + md.trimStart());
  n++;
}

// the landing page's hero example, evaluated so the output never drifts
const hero = resolve(SITE, 'src/samples/hero.decl');
if (existsSync(hero)) {
  const value = evaluate(hero);
  writeFileSync(resolve(SAMPLES, 'hero.json'), value ? JSON.stringify(value, null, 2) + '\n' : '{}\n');
}

// ---------------------------------------------------------------- the playground's examples
// One list, with the sources and the documents inlined: the landing page's
// module; the tutorials, each assembled from its untitled ```decl blocks the
// way the golden corpus assembles them, with the documents the corpus binds
// (and any `<root>_<variant>.json` beside them, such as the one a tutorial
// rejects); then the validation cases. Multi-module examples stay out: the
// playground evaluates one module.
{
  const examples = [];
  const blocks = (md) => [...md.matchAll(/```decl\n([\s\S]*?)```/g)].map((m) => m[1]).join('\n');
  if (existsSync(hero)) examples.push({ id: 'hero', label: 'services (landing page)', source: readFileSync(hero, 'utf8') });
  const manifest = JSON.parse(readFileSync(resolve(ROOT, 'tests/golden/manifest.json'), 'utf8'));
  const guideDocs = resolve(ROOT, 'tests/golden/inputs/guide');
  const seen = new Set();
  const guide = [];
  for (const e of manifest) {
    if (!e.markdown?.startsWith('docs/guide/')) continue;
    const stem = posix.basename(e.markdown, '.md');
    const md = readFileSync(resolve(ROOT, e.markdown), 'utf8');
    const title = (md.match(/^# (.+)$/m)?.[1] ?? stem).trim();
    const source = blocks(md);
    if (!source.trim()) continue;
    const bindings = (e.inputs ?? []).map((spec) => spec.split('='));
    const variants = [];
    if (!bindings.length) {
      if (!seen.has(stem)) variants.push({ suffix: '', inputs: undefined });
    } else {
      variants.push({ suffix: ` · ${bindings.map(([, f]) => posix.basename(f)).join(', ')}`, inputs: Object.fromEntries(bindings.map(([root, f]) => [root, readFileSync(resolve(ROOT, f), 'utf8')])) });
      for (const [root] of bindings)
        for (const f of existsSync(guideDocs) ? readdirSync(guideDocs).filter((x) => x.startsWith(`${root}_`) && x.endsWith('.json')).sort() : [])
          variants.push({ suffix: ` · ${f}`, inputs: { [root]: readFileSync(resolve(guideDocs, f), 'utf8') } });
    }
    for (const v of variants) {
      const id = `${stem}${v.suffix ? '-' + v.suffix.replace(/[^a-z0-9]+/gi, '-').replace(/^-|-$/g, '') : ''}`;
      if (seen.has(id)) continue;
      seen.add(id);
      seen.add(stem);
      guide.push({ id, label: `Guide: ${title}${v.suffix}`, source, ...(v.inputs ? { inputs: v.inputs } : {}) });
    }
  }
  // a tutorial's variants together, the tutorials in the guide's order
  guide.sort((a, b) => a.id.localeCompare(b.id));
  examples.push(...guide);
  for (const p of pages)
    if (p.decl) examples.push({ id: posix.basename(p.src, '.decl'), label: p.title, source: readFileSync(resolve(ROOT, p.src), 'utf8') });
  writeFileSync(resolve(SAMPLES, 'examples.json'), JSON.stringify(examples, null, 2) + '\n');
}

// ---------------------------------------------------------------- references
// Two browsable indexes derived from the specification and regenerated with
// it: every std function with its signature, and every diagnostic code
// with its condition. Each row links back to the chapter it came from.
const cells = (row) => row.trim().slice(1, -1).split(/(?<!\\)\|/).map((c) => c.trim());
// Starlight's heading anchors (github-slugger): lowercase, punctuation dropped, each space a hyphen
const anchor = (heading) => heading.toLowerCase().replace(/`/g, '').replace(/[^\p{L}\p{N} -]/gu, '').replace(/ /g, '-');
const toc = { minHeadingLevel: 2, maxHeadingLevel: 2 };

{
  const md = readFileSync(resolve(ROOT, 'docs/specification/13_stdlib.md'), 'utf8');
  const chapter = `${BASE}/specification/13_stdlib/`;
  let body = `Every function of \`std\`, indexed from [13. Standard Library](${chapter}), the normative chapter; each namespace links to the section that states its semantics in full. The SI unit catalog is declarations, not functions: [§13.10](${chapter}#${anchor('13.10 `std.units` — the SI catalog')}).\n`;
  let ns = null, inTable = false, count = 0;
  for (const line of md.split('\n')) {
    const h = line.match(/^## (13\.\d+ `std\.(\w+)`)$/);
    if (h) { ns = h[2]; inTable = false; body += `\n## \`std.${ns}\`\n\n[§${h[1].split(' ')[0]}](${chapter}#${anchor(h[1])})\n\n| Function | Signature | Semantics |\n|---|---|---|\n`; continue; }
    if (line.startsWith('## ')) ns = null;
    if (!ns) continue;
    if (/^\| Signature \| Semantics \|/.test(line)) { inTable = true; continue; }
    if (inTable && /^\|---/.test(line)) continue;
    if (inTable && line.startsWith('| `')) { const [sig, sem] = cells(line); const name = sig.replace(/`/g, '').match(/^[a-z_]+/)[0]; body += `| \`std.${ns}.${name}\` | ${sig} | ${sem} |\n`; count++; continue; }
    if (inTable && !line.startsWith('|')) inTable = false;
  }
  write('reference/stdlib', frontmatter({ title: 'Standard library', slug: 'reference/stdlib', description: `The ${count} functions of std, indexed from the specification.`, editUrl: false, tableOfContents: toc }) + body);
}
{
  const md = readFileSync(resolve(ROOT, 'docs/specification/12_errors.md'), 'utf8');
  const chapter = `${BASE}/specification/12_errors/`;
  const registry = md.slice(md.indexOf('## 12.4 Registry'), md.indexOf('## 12.5'));
  let body = `Every code an implementation may report, indexed from [12. Errors and Diagnostic Codes](${chapter}) §12.4, the normative registry; the bands (§12.1), the report format (§12.2), and the ordering rules (§12.3) are stated there. Codes are stable and the registry is append-only. A code listed under more than one heading in the chapter appears here once, at its first condition.\n`;
  const seen = new Set();
  const bands = [];
  for (const line of registry.split('\n')) {
    const h = line.match(/^### (.+)$/);
    if (h) { bands.push({ title: h[1], rows: [] }); continue; }
    const r = line.match(/^\| ([EWI]\d{4}) \| (.*) \|$/);
    if (r && bands.length && !seen.has(r[1])) { seen.add(r[1]); bands.at(-1).rows.push(`| \`${r[1]}\` | ${r[2]} |`); }
  }
  for (const b of bands) if (b.rows.length) body += `\n## ${b.title}\n\n| Code | Condition |\n|---|---|\n${b.rows.join('\n')}\n`;
  write('reference/diagnostics', frontmatter({ title: 'Diagnostic codes', slug: 'reference/diagnostics', description: `The ${seen.size} diagnostic codes, indexed from the specification's registry.`, editUrl: false, tableOfContents: toc }) + body);
}
n += 2;

console.log(`synced ${n} pages into ${posix.relative(ROOT, OUT)} (base ${BASE})`);
